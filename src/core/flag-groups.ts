function tail(flag: string): string {
  return flag.startsWith(PREFIX) ? flag.slice(PREFIX.length) : flag;
}

function hit(flag: string, parts: readonly string[], loose = false): boolean {
  const name = tail(flag);
  return parts.some((part) => name === part || name.startsWith(part + '_') || (loose && name.startsWith(part)));
}

function groupForFlag(flag: string): GroupFlag | undefined {
  if (!(KNOWN_FLAGS as readonly string[]).includes(flag)) {return undefined;}
  if (hit(flag, AI, true)) {return 'FULLSHIELD_EXPERIMENTAL_AI';}
  if (hit(flag, RUNTIME)) {return 'FULLSHIELD_EXPERIMENTAL_RUNTIME';}
  if (hit(flag, REPORTS)) {return 'FULLSHIELD_EXPERIMENTAL_REPORTS';}
  if (hit(flag, SUPPLY)) {return 'FULLSHIELD_EXPERIMENTAL_SUPPLY';}
  return 'FULLSHIELD_EXPERIMENTAL_SAST_EXTRA';
}

function membersOf(group: GroupFlag): readonly string[] {
  return KNOWN_FLAGS.filter((flag) => groupForFlag(flag) === group && flag !== group);
}

/** 3.6.1: every group flag, including SUPPLY, turns on its unset members. */
const FAN_OUT: readonly GroupFlag[] = GROUP_FLAGS;

/** Turn on unset members. Does not overwrite a value that is already set. */
export function applyFlagGroups(env: NodeJS.ProcessEnv = process.env): void {
  for (const group of FAN_OUT) {
    if (env[group] !== '1') {continue;}
    for (const member of membersOf(group)) {
      if (env[member] === undefined) {env[member] = '1';}
    }
  }
}
