export type NpmGroupName = keyof typeof NPM_GROUPS;

const PHASE_TO_GROUP = new Map<string, NpmGroupName>();
for (const group of Object.keys(NPM_GROUPS) as NpmGroupName[]) {
  for (const flag of NPM_GROUPS[group]) {
    PHASE_TO_GROUP.set(flag, group);
  }
}

/** Group flag that aliases `flag`, or undefined when `flag` is not a phase check. */
export function groupForPhaseFlag(flag: string): NpmGroupName | undefined {
  return PHASE_TO_GROUP.get(flag);
}
